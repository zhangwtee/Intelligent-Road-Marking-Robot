#ifndef __HEADING_H
#define __HEADING_H

#include "stm32f10x.h"

/* ==========================================================================
 * 航向估计 + 直线闭环
 *
 * 解决的问题：车走不了直线。
 *
 * 根因不是"四个轮子标定不准"，是**没有任何东西知道车头现在朝哪**。
 * 四个开环步进，脉冲发多少就以为走多少，轮子打滑、地面不平、某个轮子
 * 直径差 1mm，全都没人管，误差一路累积到五米外就是半米。
 *
 * 陀螺仪给的是角速度，积分成角度。这一层做三件事：
 *   1) 采样和积分（含零偏处理，这是精度的全部来源）
 *   2) 段起点对齐（每一段直线的起点航向记为 0）
 *   3) 把"偏了多少度"换算成"左右轮该差多少毫米"
 *
 * 执行仍然走 Motion_Trim —— 它能在运动中改目标脉冲而不清进度，
 * 所以纠偏不需要停车。停一次，泵就在原地出一摊漆。
 *
 * ---- 为什么陀螺仪在下位机，不在上位机 ----
 * 上位机走串口，9600 波特下一帧 10 字节要 10ms，加上树莓派调度抖动，
 * 拿来闭合一个 10ms 的控制环根本不成立。航向是快的量，必须在采集它的
 * 那颗芯片上闭环。上位机管慢的（视觉判破损、路径规划），下位机管快的
 * （航向、脉冲），这才是当初分两层的意义。
 * ========================================================================== */

/* ---- 采样与积分 ---- */
#define HDG_SAMPLE_MS           10      /* 采样周期。和 MPU 的 100Hz 输出对齐 */
#define HDG_DT_MAX_MS           100     /* 超过这个 dt 说明主循环被卡了很久，
                                         * 这段时间的姿态不可知，宁可丢也不猜 */

/* ---- 零偏 ---- */
#define HDG_CAL_SAMPLES         100     /* 上电标定样本数 = 1 秒 @100Hz */
#define HDG_CAL_SPREAD_LSB      40      /* 标定期间 (max-min) 超过 40 LSB
                                         * (≈0.6 dps) 就认为车在动，这一次不算。
                                         * 静止噪声典型只有十几 LSB。 */
#define HDG_RETRY_MS            2000    /* 标定失败/掉线后多久重试一次。
                                         * 不做"失败 N 次就放弃"：能失败的只有
                                         * "车在动"和"线松了"两种，这两种都
                                         * 会在车停下/插好之后自动变好。
                                         * 放弃反而制造一个只能发命令才能解的死状态。 */
#define HDG_STILL_DPS           1.2f    /* 电机停 + 角速度小于这个 = 静止，
                                         * 此时不积分，只更新零偏 */
#define HDG_BIAS_ALPHA          0.002f  /* 静止时零偏跟踪系数，@10ms 约 5 秒
                                         * 时间常数。MPU6050 的零偏温漂是
                                         * 分钟级的，5 秒跟得上 */

/* ---- 控制 ---- */
#define HDG_DEADBAND_DEG        0.4f    /* 小于这个角度不修。噪声级别的偏差
                                         * 修了只会让四个轮子来回抖 */
#define HDG_TRIM_ONCE_MAX_MM    20.0f   /* 单次修正上限，和 MOTION_TRIM_MAX_MM
                                         * 一致。一次给太多，内侧轮会直接停死，
                                         * 变成原地转而不是弧线修正 */
#define HDG_KP                  1.0f    /* 纯几何补偿，不加增益。
                                         * 1.0 = "需要转回 e 度，就给出转回 e 度
                                         * 所需的轮差"。实测修正不足再往上调
                                         * 到 1.2~1.5，超过 2 会来回摆。 */

/* 一次 Poll 的状态，给 OLED 和故障诊断用 */
typedef enum {
    HDG_OFF = 0,        /* 传感器没接上 / 初始化失败 */
    HDG_CALIBRATING,    /* 正在采零偏（车必须静止） */
    HDG_READY,          /* 已标定，闭环未启用 */
    HDG_CLOSED,         /* 已标定，闭环已启用 */
    HDG_FAULT           /* 跑着跑着掉线了 */
} HeadingState;

/* 初始化：配传感器 + 启动零偏标定（非阻塞，标定在主循环里推进）。
 * 返回 0 = 传感器应答正常；非 0 = MPU6050 的错误码（见 mpu6050.h）。
 * 返回非 0 也不要紧，Heading_Poll 会在车停下时自己重试。 */
uint8_t Heading_Init(void);

/* 主循环每轮调一次。内部按 HDG_SAMPLE_MS 节流，调用频率高一点没关系。 */
void Heading_Poll(void);

/* 段起点对齐：把当前累计航向记为参考点，之后 Heading_GetDeg() 从 0 开始。
 * 每段直线开始时调一次；同一段里续发 MOVE 时**不要**调，
 * 那会把已经修正掉的偏差重新变成 0，闭环就白干了。 */
void Heading_MarkReference(void);

/* 相对段起点的航向，度。右偏为正（顺时针）。
 * 未就绪时恒返回 0 —— 让调用方拿到 0 比拿到一个没意义的角度安全。 */
float Heading_GetDeg(void);

/* 累计航向（上电以来），度。调试和"到底转了多少度"用。 */
float Heading_GetAbsoluteDeg(void);

/* 最近一次采样得到的角速度，dps，已去零偏。 */
float Heading_RateDps(void);

HeadingState Heading_GetState(void);
uint8_t      Heading_IsReady(void);     /* 已标定（能不能信） */
uint8_t      Heading_IsEnabled(void);   /* 闭环开着（会不会动轮子） */

/* 开关闭环。只在已标定时才能真正打开 —— 没标定就开等于用一个随机的
 * 零偏去纠偏，车会往一个方向一直偏。返回实际生效后的状态。 */
uint8_t Heading_SetEnabled(uint8_t en);

/* 重新标零（车必须停着）。
 * 返回 0 = 已开始；1 = 车在动，不能标；2 = 传感器不在线。 */
uint8_t Heading_Recalibrate(void);

/* 因主循环卡顿而丢掉的积分次数。
 * 恒为 0 是正常的。涨起来说明有别的地方在长时间阻塞主循环
 * （某段延时、OLED 整屏刷新、串口死等），角度精度会跟着下降，
 * 状态帧里带出去，不用等到车走歪了才发现。 */
uint16_t Heading_DroppedSamples(void);

/* 本轮该给的差速修正量，毫米，正 = 让车头向右。
 * 0 表示：没就绪 / 没开闭环 / 在死区内 / 本轮还没到修正节拍。
 *
 * 这个函数只算不执行，执行由调用方交给 Motion_Trim —— 这样固件里
 * "算"和"动"是分开的，测试可以在没有电机的情况下验证控制律。 */
float Heading_TrimDeltaMm(void);

/* 由"单侧多走了多少毫米"和"车实际转了多少度"反算左右轮中心距。
 * 轮距是陀螺仪闭环唯一的机械参数，标定办法见 calib.h。
 * 返回值 0 表示这次测量不可信（角度太小、算出来的值离谱），不要采用。 */
float Heading_EstimateTrackWidth(float diff_mm, float turned_deg);

/* 运行时轮距。默认取 calib.h 的 CALIB_TRACK_WIDTH_MM，
 * 现场用 CMD_GYRO 子命令 3 实测出更准的值后就写这里。
 *
 * 只存在 RAM：掉电回到 calib.h 的值。这是有意的 —— 一个没经过复核的数字
 * 不该悄悄留在一个看不见的地方。觉得准了，就抄进 calib.h 固化。
 * 超出 150~1500mm 的值会被拒收（返回 0），防止一次测量错误把闭环调飞。 */
uint8_t Heading_SetTrackWidth(float mm);
float   Heading_GetTrackWidth(void);

#endif
