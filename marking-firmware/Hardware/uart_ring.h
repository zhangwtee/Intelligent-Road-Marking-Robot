#ifndef __UART_RING_H
#define __UART_RING_H

#include "stm32f10x.h"

/* ==========================================================================
 * 串口环形缓冲 —— 单生产者 / 单消费者，无锁
 *
 * 同一个结构两个方向都用，只是谁写谁读反过来：
 *   接收（rx1 / rx2）：中断 Put、主循环 Get。
 *   发送（tx1 / tx2）：主循环 Put、TXE 中断 Get。
 *
 * 为什么接收要有这个文件：
 *   原来每路串口只有【一个字节变量 + 一个标志位】。中断写、主循环读，
 *   同一时刻只能记住一个字节。主循环一圈虽然只有几十微秒，但 OLED 刷一屏
 *   (软件 I2C，约 80~100ms)、舵机插值时都会停住。这期间到两个字节，
 *   第二个直接把第一个覆盖掉 —— 不报错、不告警，静默丢一条命令。
 *   上位机每 2 秒才发一条，所以平时看不出来；一旦手机 APP 按住连发
 *   (U/R/Y/Z/A/X 需要重复发送续命，见 system.c 的 JOG_TIMEOUT_MS)，
 *   或者发送侧一帧 10 字节要占 10.4ms 的线上时间，这个问题立刻变成
 *   "发了没反应"。
 *
 * 为什么无锁是安全的：
 *   head 只由生产者写、tail 只由消费者写。两边都只写自己的指针，
 *   读对方的指针是一次对齐的 16 位读，在 Cortex-M3 上是原子的。
 *   所以不需要 __disable_irq()，中断延迟也不受影响。
 *   （对比：原来 TakeRxData 用临界区，是因为数据变量和标志位要一起读，
 *     那是两个变量。环形缓冲把"有没有数据"和"数据是什么"合并成一个指针差，
 *     临界区就不需要了。）
 *
 * 满了怎么办，两个方向不一样：
 *   接收：中断里不能等，丢弃【新】字节。旧命令先到先服务，丢最旧的会让
 *         "按了急停 T"被后面的噪声挤掉，方向反了。
 *   发送：主循环可以等，调用方（USART.c 的 Uart_TxPut）发现 Put 失败就
 *         转一圈再来，直到 TXE 中断腾出位置 —— 少一个字节对端要靠 300ms
 *         静默期重新同步，不能丢。
 *
 *   overflow 记的是"满了几次"：接收环上它等于丢弃的字节数（正常恒为 0，
 *   非 0 说明主循环被什么长动作卡住了）；发送环上它只是重试次数，不丢数据。
 * ========================================================================== */

/* 必须是 2 的幂（用 & 取模，比 % 快且不会引入除法库）。
 * 64 = 可用 63 字节 ≈ 9600 波特率下 65ms 的流量。
 * 这个深度不需要更大：它要接住的不是"持续高速数据"，而是
 * "主循环被某个长动卡住一次的这段时间"。 */
#define UART_RING_SIZE   64

typedef struct {
    uint8_t           buf[UART_RING_SIZE];
    volatile uint16_t head;      /* 写指针，只由生产者改 */
    volatile uint16_t tail;      /* 读指针，只由消费者改 */
    volatile uint16_t overflow;  /* 满过几次（接收环上等于丢弃数），只增不减 */
} UartRing;

void     UartRing_Init(UartRing *r);

/* 生产者调用。返回 1 = 存进去了，0 = 缓冲满（接收环丢弃并计数，发送环由调用方重试）。 */
uint8_t  UartRing_Put(UartRing *r, uint8_t byte);

/* 消费者调用。返回 1 = 取到一个字节，0 = 缓冲空。 */
uint8_t  UartRing_Get(UartRing *r, uint8_t *out);

/* 消费侧调用：看第 offset 个待处理字节（0 = 队首），不消费。
 * 返回 1 = 有这个字节，0 = 不够。
 * 协议解析需要它：先看首字节是不是帧头，再决定丢 1 个还是丢一整帧，
 * 中间不能把数据取出来又塞回去（那样会把顺序打乱）。 */
uint8_t  UartRing_Peek(UartRing *r, uint16_t offset, uint8_t *out);

/* 消费侧调用：丢弃 n 个字节（包括已经 Peek 过的）。
 * 只有主循环改 tail，所以和 Get 一样不需要临界区。 */
void     UartRing_Drop(UartRing *r, uint16_t n);

/* 当前积压字节数。 */
uint16_t UartRing_Count(UartRing *r);

/* 累计丢弃字节数，用于判断主循环是否被卡住过。 */
uint16_t UartRing_Overflow(UartRing *r);

#endif
