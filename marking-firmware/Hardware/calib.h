#ifndef __CALIB_H
#define __CALIB_H

/*
 * 标定值集中定义
 * ============================================================================
 * 规则：每个数旁边必须能回答三个问题
 *   1. 怎么测出来的（工具 / 方法 / 样本数）
 *   2. 什么时候测的
 *   3. 什么条件变了之后它会失效
 *
 * 没有出处的数不是标定值，是猜测。
 * ============================================================================
 *
 * 当前状态：这三个参数是【由旧代码四个硬编码脉冲数联立反解】出来的。
 * 反解的意义：如果四个互相独立的常量能被同一组参数同时解释，说明当年的
 * 标定是自洽的，只是没把单位和物理含义写下来。
 *
 * 反解结果（假设细分 = 8，即 1600 步/圈）：
 *   轮径 101.9 mm  转弯半径 382 mm
 *   代入后：26500->5302.1mm  12500->2501.0mm  3000->90.03度  5000->1000.4mm
 *   四个旧值全部吻合，最大误差 0.05%。
 *
 * 但自洽不等于正确。反解只保证能凑出旧值，不保证和实物一致。请实测：
 *   轮径  ：卷尺绕轮一周量周长，除以 3.14159
 *   细分  ：驱动器面板 MStep，或数电机转一圈的脉冲数
 *   转弯半径：把车架起来，四个轮子中心到车体旋转中心的距离
 * 若实测轮径与 101.9 mm 相差超过 2 mm，说明细分不是 8，四个值要一起重算。
 * ============================================================================
 */

/* ---------- 机械参数（待实测） ---------- */
#define CALIB_WHEEL_DIA_MM      101.9f   /* 待实测：轮子周长 / PI */
#define CALIB_STEPS_PER_REV     1600     /* 200 步/圈 x 8 细分，待确认驱动器 MStep */
#define CALIB_TURN_RADIUS_MM    382.0f   /* 由 3000 脉冲 / 90 度反算，待实测 */

/* ---------- 每轮补偿系数（1.000 = 基准轮） ----------
 * 用途：四个轮子直径不一致时，走同样的脉冲会走不同的距离。
 * 求法：让车直走 5 米，量每个轮子实际滚过的距离，k_i = 基准距离 / 该轮距离。
 * 注意：系数偏离 1.000 超过 2% 时，斜坡的四路同步会明显失配，
 *       应该先检查轮子是不是装错了，而不是靠系数硬补。
 */
#define CALIB_WHEEL_K1          1.000f   /* 左前 */
#define CALIB_WHEEL_K2          1.000f   /* 右前 */
#define CALIB_WHEEL_K3          1.000f   /* 左后 */
#define CALIB_WHEEL_K4          1.000f   /* 右后 */

/* ---------- 陀螺仪闭环：左右轮中心距 ----------
 *
 * 这是航向闭环里唯一的机械参数。作用只有一个：把"车头偏了 e 度"
 * 换算成"左右轮该差多少毫米"（Δd = e_rad × 轮距）。
 *
 * 当前值 500.0f 是【估的】，不是量出来的 —— 从 CALIB_TURN_RADIUS_MM
 * 反推：若四轮正方形布局，382 × √2 ≈ 540；按车体宽度估计取 500。
 * 这就是个占位值，装好陀螺仪之后必须实测。
 *
 * 实测办法（不用拆车）：
 *   1. 上电，等 OLED 上陀螺仪状态变成 OK（零偏标定完成）
 *   2. 发一条 MOVE：左轮 300mm、右轮 0mm（单侧差速，车会绕右侧转）
 *   3. 读航向帧里转过的角度 θ（度）
 *   4. 轮距 L = 300 / (θ × π/180)
 *      例：转了 33 度 -> L = 300 / 0.576 = 521 mm
 *
 * 也可以让固件自己算：发 CMD_GYRO 子命令 3，它走完 300mm 之后
 * 直接用 Heading_EstimateTrackWidth() 反算并回报，不用手算。
 *
 * 这个数错 20% 的后果不是"走不直"，而是"永远修一半"或者"修过头来回摆"：
 *   - L 偏小 -> 算出来的修正量偏小 -> 车一直偏，但偏得比不修少
 *   - L 偏大 -> 修正过头 -> 车头左右摆，看起来像陀螺仪坏
 * 所以它是现场可以调的量，不必一次标到位；但调之前要先确认零偏是准的，
 * 否则会把"零偏错"误当成"轮距错"来调。
 *
 * 失效条件：换底盘、改轮距、四个轮子换成不同直径的。 */
#define CALIB_TRACK_WIDTH_MM    500.0f

/* ---------- 工艺行程（逻辑值，不是标定值） ---------- */
#define CALIB_PAINT_LONG_MM     5300.0f  /* 车位长边 */
#define CALIB_PAINT_SHORT_MM    2500.0f  /* 车位短边 */
#define CALIB_TURN_DEG          90.0f    /* 转角 */

/* ---------- 补喷长度档位（'1'~'5' 选择） ---------- */
#define CALIB_RESPRAY_L1_MM      200.0f
#define CALIB_RESPRAY_L2_MM      400.0f
#define CALIB_RESPRAY_L3_MM      600.0f
#define CALIB_RESPRAY_L4_MM      800.0f
#define CALIB_RESPRAY_L5_MM     1000.0f
#define CALIB_RESPRAY_DEFAULT    5       /* 上电默认档位 */

/* ---------- 时序参数（毫秒） ---------- */
#define CALIB_BOOT_SILENCE_MS   10000    /* 上电后忽略命令的时长，避开串口毛刺 */
#define CALIB_CMD_TIMEOUT_MS     3000    /* 运动态超过此时长无合法字节则停机 */
#define CALIB_JOG_TIMEOUT_MS     2000    /* 遥控点动超时 */

#endif
