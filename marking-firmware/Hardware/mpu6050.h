#ifndef __MPU6050_H
#define __MPU6050_H

#include "stm32f10x.h"

/* ==========================================================================
 * MPU6050 陀螺仪驱动（软件 I2C，只用陀螺仪部分）
 *
 * 引脚：PB10 = SCL，PB11 = SDA
 *   电机占 PA6/PA0/PA1/PC6 和四个 DIR，舵机占 PB6/PB7，OLED 占 PB8/PB9，
 *   串口占 PA2/PA3/PA9/PA10，泵和蜂鸣器占 PB13/PB14，心跳灯占 PB15。
 *   从 C8T6 换到 ZET6 之后，PB10/PB11 仍然可用（是 I2C2 的 SCL/SDA），
 *   所以这次驱动一行都没改。要挪到别的脚，只改下面四个宏。
 *
 * 为什么软件 I2C 不用硬件 I2C：
 *   1) I2C1 的默认引脚 PB6/PB7 被 TIM4 的两个舵机通道占了，重映射口
 *      PB8/PB9 又被 OLED 占了。C8T6 和 ZET6 上都拼不出一组完整的硬件 I2C1。
 *   2) F103 的硬件 I2C 有著名的 errata，从机在传输中间复位时总线会锁死，
 *      只能整体复位 I2C 外设。软件 I2C 遇到这种情况发 9 个时钟就能救回来。
 *   3) 本项目 100Hz、一次 6 字节，软件 I2C 的开销完全够（约 0.6ms/次）。
 * ========================================================================== */

#define MPU_SCL_PORT    GPIOB
#define MPU_SCL_PIN     GPIO_Pin_10
#define MPU_SDA_PORT    GPIOB
#define MPU_SDA_PIN     GPIO_Pin_11

/* 量程 ±500 dps 对应的换算系数。
 * 换量程时必须同时改 mpu6050.c 里的 MPU_GYRO_FS_SEL，否则角度会整体
 * 差一个倍数 —— 而且不会有任何报错，只是车越走越歪。 */
#define MPU_GYRO_LSB_PER_DPS    65.5f
#define MPU_GYRO_FS_DPS         500.0f

/* ---------- 返回码 ----------
 * 布尔返回值在这里不够用：接反、没供电、地址不对、芯片不是 6050，
 * 这四种故障在串口上表现完全一样（都是"没数据"），但现场处理方式不同。
 * 分开报，OLED 上直接写出来，比让人拿万用表猜快得多。 */
#define MPU_OK              0
#define MPU_ERR_I2C         1   /* 从机无应答：没接、接反、没供电、上拉缺失 */
#define MPU_ERR_ID          2   /* WHO_AM_I 不是 0x68：不是 MPU6050，或 AD0 被拉高 */
#define MPU_ERR_CONFIG      3   /* 配置写进去又读不回来：电源不稳或总线干扰 */
#define MPU_ERR_NOT_INIT    4   /* 还没初始化成功就被调用 */

/* 初始化。返回上面四个码之一。
 * 内部依次做：引脚初始化 -> 总线恢复 -> 软复位 -> 唤醒并选时钟源 ->
 * 量程/DLPF/采样率 -> 回读校验 -> WHO_AM_I。
 * 任何一步失败都返回错误码并且不再往下做 —— 一个没配好的陀螺仪给出的
 * 角度比不给还危险（它看起来是好的）。 */
uint8_t MPU6050_Init(void);

/* 运行中掉线后的快速重连。
 *
 * 和 MPU6050_Init 的区别：不做软复位、不做上电等待，全程约 1ms。
 * 这个函数会在主循环里被调用（车停着的时候），而 Init 里的 230ms 粗延时
 * 会让串口接收环形缓冲（64 字节 @9600 ≈ 66ms）直接溢出丢命令。
 *
 * 做的事：重设引脚 -> 9 时钟总线恢复 -> WHO_AM_I -> 重写配置 -> 回读校验。
 */
uint8_t MPU6050_Recover(void);

/* 读 WHO_AM_I。正常值 0x68。 */
uint8_t MPU6050_WhoAmI(uint8_t *id);

/* 一次突发读 6 字节，拿到同一采样时刻的 X/Y/Z 三轴原始值。
 *
 * 为什么不照课堂例程那样一个寄存器一个寄存器读：例程读 6 个轴要发起
 * 6 次独立传输，前后差几百微秒。车在转的时候，这 6 个值根本不是同一个
 * 姿态下的样本。本项目的用法是「角速度 x 时间」积分成角度，
 * 采样时刻对不上就是直接往角度里灌误差。
 *
 * 也不用 FIFO：FIFO 要额外配置和溢出处理，100Hz 轮询已经够用，
 * 多一层状态机只会在现场多一种"卡住"的方式。 */
uint8_t MPU6050_ReadGyro(int16_t *gx, int16_t *gy, int16_t *gz);

/* 只要 Z 轴（车体偏航）。读 6 字节是因为寄存器是连续的，
 * 只读 Z 要 2 字节，省不下那一次 START/STOP 的时间。 */
uint8_t MPU6050_ReadGyroZ(int16_t *gz);

/* 最近一次初始化是否成功（给别的模块判断，不用重复调 Init）。 */
uint8_t MPU6050_IsOnline(void);

/* 失败累计次数。上电后一直为 0，跑着跑着涨起来说明接线松动或干扰变大了，
 * 状态帧里带出去，上位机能在"角度开始飘"之前就看见。 */
uint16_t MPU6050_ErrorCount(void);

#endif
