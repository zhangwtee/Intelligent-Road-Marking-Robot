#ifndef __CFG_H
#define __CFG_H

#include "stm32f10x.h"

/* ==========================================================================
 * 掉电保存：速度档位 + 断点位（画车位续画用）
 *
 * 速度和断点各占两页，一主一备，交替写。
 *
 * 为什么不能共用一页：以前两个挤在最后一页里，写一次要先把整页擦掉、
 * 再把两样从头写回去。擦完还没写完的那一刻掉电，两样一起没了 —— 速度回
 * 默认档，断点也没了，而校验字只能判出"这条无效"，保留不了上一份。
 * 拆成四页之后，每次只动"自己那两页里旧的那页"，另一页全程有效。最坏
 * 情况变成"这一次没存上"，而不是"上一份也没了"。
 *
 * 布局（512K 镜像的最后四页，2KB 一页）：
 *   0x0807E000  速度 A      0x0807E800  速度 B
 *   0x0807F000  断点 A      0x0807F800  断点 B
 *
 * 每页带一个自增序号。读的时候两页都读、挑序号大且校验通过的那份；
 * 写的时候写另一页。任何时刻至少有一份完整数据。
 *
 * 写一次要一整个页时间（F103 擦一页期间取指是停的），所以调用方必须在
 * 车停着的时候写 —— 见 system.c 的 SpeedSaveService / PaintResumeService，
 * 以及画车位每条边开头那一次（那一刻车刚停下、泵还关着）。
 * ========================================================================== */

/* 中断点记录。字段统一用毫米，1mm 的分辨率对"还剩多远"够用，
 * 也比脉冲数好读。
 *
 * 左右分开存：急停那一刻两侧本来就不等长，差速纠偏改的就是左右各自的
 * 目标脉冲，只记一路等于把那笔还没走完的差速丢掉。 */
typedef struct {
    uint8_t  valid;         /* 1 = 这条记录有效 */
    uint8_t  step;          /* PaintStep 的当前值（EDGE1 ~ EDGE4） */
    uint8_t  heading;       /* 断点那条边当时有没有在纠偏 */
    uint16_t left_mm;       /* 左边还剩多少毫米 */
    uint16_t right_mm;      /* 右边还剩多少毫米 */
    uint16_t len_mm;        /* 车位长边长度，续完这条边还要用 */
    uint16_t wid_mm;
} CfgResume;

/* 初始化时读到有效值就返回 1，arr 已经填好；0 表示没存过 / 存坏了。 */
uint8_t Cfg_LoadSpeed(uint16_t *arr);

/* 写进去，带读回校验。返回 1 = 真的写成功了。
 * flash 写失败不会报错，只会写不进速度一样 —— 调用方拿这个返回值判断。 */
uint8_t Cfg_SaveSpeed(uint16_t arr);

/* flash 里现在存的是多少。没有有效值返回 0。
 * ARR 的合法范围是 150~1500，0 撞不上，调用方可以直接用它判断"没存过"。 */
uint16_t Cfg_GetSavedSpeed(void);

/* 读回断点。返回 1 = 有条有效断点；0 = 没有，或者存的值不合理。 */
uint8_t Cfg_LoadResume(CfgResume *rec);

/* 写断点（rec->valid = 1），或抹掉（rec->valid = 0）。
 * 返回 1 = 真的写成功了。失败之后 flash 里还剩什么由调用方决定怎么处理。 */
uint8_t Cfg_SaveResume(const CfgResume *rec);

/* 抹掉断点。没有断点时直接返回 1，不必擦一页。 */
uint8_t Cfg_ClearResume(void);

#endif
