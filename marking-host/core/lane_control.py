"""标线跟踪控制律：把「线歪了多少」翻译成「左右轮各走多少」。

为什么这个东西值得单独一个文件
------------------------------
它是整台车里唯一一处「数学直接决定机器怎么动」的地方。判破损的阈值错了，
最多是少补一段漆；这里的增益错了，车会跑出一条越来越弯的弧，而且现场
看不出来是从哪一步开始错的 —— 因为每一步看起来都只是在"稍微修正一下"。

所以它必须：不依赖 cv2、不依赖 Qt、不碰串口，能拿几个数字直接跑。

两个输入，一个输出
------------------
    heading  标线主方向与车头方向的夹角（度）。线在画面里向右倾 -> 正
    lateral  标线中心相对画面中心的横向偏移，归一化到 [-1, 1]。线在右边 -> 正

    trim     整车附加的差速量（毫米）。正 = 车头向右，负 = 向左

为什么是"两个输入"
------------------
只用航向：能走直，但如果一开始就和线平行错开 10cm，会一直平行错开下去。
        画标线要的是"压着原来的线"，平行偏移同样是废品。
只用横向：反应慢，而且车会追着线"甩" —— 横向误差一出现就往回打，打过头
        再往另一边打，蛇形。因为横向误差是航向误差积分出来的，直接对它
        做比例控制相当于对一个积分环节做比例控制，天生振荡。

两个一起用，本质是 PD：航向是 P（当前偏了多少），横向是 I 的替代品
（历史上偏了多少的结果）。没有单独的 D —— 差速命令本身就是速度环的
输入，再加 D 会和固件的脉冲执行互相打架。

一个必须知道的物理约束
--------------------
固件的四个轮子共用 TIM3 的一个 ARR，也就是四路脉冲频率永远相同。这意味
着左右轮**不可能同时到达各自的目标脉冲数**：谁的目标小，谁先停。
所以"差速"在本机上表现为"内侧轮提前停下"，不是平滑的弧线。

由此得到两条硬规矩：

  1. 单次差速必须小。差 20mm 在 500mm 轮距上等于 2.3 度，已经是"一段
     200mm 里偏 2.3 度"。再大就不是修正，是拐弯。
  2. 不能让它累积。如果整条 5.3 米只算一次差速，50 段之后内侧轮会提前
     一米停下，剩下的由外侧轮单独走 —— 车原地转 90 度。

第 2 条决定了上位机的用法：**每段重设，不是全程一次**。段尾四路计数归零，
上一段攒下的左右差自动清空。这个文件只负责算"这一段差多少"，重设由
camera_widget 的分段循环保证。
"""

import math

# ---------------- 标定参数（全工程唯一一份） ----------------
GAINS = {
    # 航向增益：偏 1 度，差速给多少毫米。
    # 3.0 的物理含义：偏 5 度 -> 差 15mm -> 一段 200mm 内转 1.7 度。
    # 也就是"偏 5 度大约要 3 段、60cm 才能纠回来"，这个响应速度对
    # 0.16m/s 的车刚好，再快就会过冲（一段就从 +5 度冲到 -3 度）
    #
    # 为什么不是几何值：如果按"一步转回来"算，500mm 轮距下应该是
    # 1 度 -> 8.73mm（= 500 × π/180）。这里只给 3.0，不是算错了。
    #   1) 视觉的角度是从像素拟合出来的，线本身不直、反光、阴影都会让它
    #      抖 1~2 度。按几何值一步到位，等于把噪声放大成车身摆动。
    #   2) 视觉每 200mm 才纠一次（1.2 秒），一步到位很容易冲过头。
    # 下位机的陀螺仪闭环用的是几何值 8.73 —— 它 100ms 一次、噪声小得多，
    # 有这个条件。两者数值不同是有意的，不要去"统一"它们。
    "K_HEADING_MM_PER_DEG": 3.0,

    # 横向增益：线偏到画面边缘（ratio=1）时给多少毫米。
    # 这个值的上限被 MAX_TRIM_MM 卡住，所以实际起作用的是它和航向项的比例。
    # 偏小：平行偏移要很久才纠回来。偏大：会蛇形（见文件头）。
    "K_LATERAL_MM": 18.0,

    # 单次差速上限。必须 <= 固件 proto.h 的 PROTO_TRIM_MAX_MM，
    # 否则帧会被固件判越界，回 ERR_RANGE，而车的表现是"完全不纠"。
    "MAX_TRIM_MM": 20.0,

    # 死区：|trim| 低于这个值就当 0。
    # 不是为了省 CPU，是为了不让车在"直线上"也一直小幅左右摆 ——
    # 开环步进每次改目标都是一次真实的机械动作，没有反馈能把它抹平。
    "DEADBAND_MM": 0.8,

    # 相邻两段之间差速最多变多少。
    # 视觉会跳（反光、阴影、线断了又接上），一帧坏数据就给出 20mm 的
    # 反向修正，车会当场抖一下。限住每段的变化量，坏帧的影响就衰减成
    # 一次很小的扰动，下一帧好数据自然拉回来。
    "MAX_STEP_MM": 8.0,
}

# 车头方向和标线方向的安装偏角（度）。
# 相机装歪了、或者相机不是严格朝正前方，就在这里补。
# 正的偏角表示"相机往右歪了"，所以算出来的航向要减掉它。
CAMERA_YAW_OFFSET_DEG = 0.0

# 轮距（左右轮中心距，毫米）。只用于把差速折算成角度，做诊断显示用，
# 不参与控制 —— 控制直接输出毫米。改这里不影响行为，影响的是日志里的角度。
TRACK_WIDTH_MM = 500.0


def clamp(value, low, high):
    return low if value < low else (high if value > high else value)


def heading_error_deg(vx, vy, yaw_offset_deg=None):
    """标线主方向向量的 x 分量 -> 航向偏差（度）。0 = 线与车头平行。

    为什么用 vx 而不是角度：PCA 给出的主轴方向是没有正负的，(0,1) 和 (0,-1)
    是同一条线。先 atan2 再归一化到 (-90, 90] 的话，"线在左边倾"和"线在右边
    倾"会落到同一个数上，符号没了。而符号正是纠偏要的东西。

    但光看 vx 也不行 —— v 和 -v 是同一条线，vx 却是相反的符号。所以先把
    v 翻到"朝车前方"（vy >= 0）再取 atan2。这一步是必须的：numpy 的
    eigh 在不同数据上给出的特征向量符号是不确定的，同一根线这次给 +30 度、
    下次给 -30 度，车就会左右乱打，而且看起来毫无规律。

    参数是单位向量，调用方从 PCA 特征向量直接取，不要传角度。
    """
    if yaw_offset_deg is None:
        yaw_offset_deg = CAMERA_YAW_OFFSET_DEG

    # 把 v 翻到朝前（画面里 y 向下，所以"朝前"是 vy >= 0）
    if vy < 0:
        vx = -vx
        vy = -vy

    # vy 为 0 时线是横的（偏差 ±90 度），atan2 给出正确的边界值
    return math.degrees(math.atan2(vx, vy)) - yaw_offset_deg


def lateral_error_ratio(cx, image_width):
    """标线中心的横向偏移，归一化到 [-1, 1]。中心在画面右侧为正。

    用归一化而不是像素：不需要标定"一个像素几毫米"。代价是增益的含义
    变成"满偏时给多少毫米"，而不是物理量 —— 对比例控制来说无所谓，
    反正最后还是要现场调 GAINS。
    """
    if image_width <= 0:
        return 0.0
    return clamp((cx - image_width / 2.0) / (image_width / 2.0), -1.0, 1.0)


def trim_mm(heading_deg, lateral_ratio, previous=0.0):
    """两个误差 -> 这一段应该给多少差速（毫米）。正 = 向右。

    previous 是上一段实际发出去的值。带上它是为了限变化率：
    不传就是无记忆的比例控制，传了就是"带速率限制的比例控制"。
    """
    g = GAINS

    raw = (g["K_HEADING_MM_PER_DEG"] * heading_deg
           + g["K_LATERAL_MM"] * lateral_ratio)

    if abs(raw) < g["DEADBAND_MM"]:
        raw = 0.0

    raw = clamp(raw, -g["MAX_TRIM_MM"], g["MAX_TRIM_MM"])

    max_step = g["MAX_STEP_MM"]
    step = clamp(raw - previous, -max_step, max_step)

    return clamp(previous + step, -g["MAX_TRIM_MM"], g["MAX_TRIM_MM"])


def segment_lengths(base_mm, trim):
    """把差速摊到左右轮，返回 (left_mm, right_mm)。

    trim 是整车的附加量，摊到两侧各一半：左边 +trim/2，右边 -trim/2。
    所以两边差的绝对值是 trim，而车中心走的距离仍然是 base_mm。

    左边多走 = 车头向右，这是固件 motion.c 里 MOTION_TRIM_SIGN 的约定。
    现场要是发现纠偏越纠越歪，先别改这里 —— 先确认相机是不是装反了，
    再考虑那个宏。
    """
    half = trim / 2.0
    return base_mm + half, base_mm - half


def will_stall(base_mm, trim):
    """这一段的参数会不会让某一侧根本走不动。

    内侧轮的目标 = base - |trim|/2。差速给满 20mm、段长 20mm 的时候，
    内侧轮目标就是 0 —— 固件那边 SetPulse(0) 等于停机，于是这一段变成
    "单边驱动 + 原地转"，和预期的缓弧完全是两回事。

    段长必须远大于差速，这条检查就是拦这个的。
    """
    left, right = segment_lengths(base_mm, trim)
    return left <= 0 or right <= 0


def trim_to_angle_deg(trim):
    """差速折算成"这一段车头转过多少度"。只用于日志和画面上显示，
    不参与控制。"""
    if TRACK_WIDTH_MM <= 0:
        return 0.0
    return math.degrees(trim / TRACK_WIDTH_MM)
